/**
 * @param names - CSS property names (or regex fragments) to match.
 * @returns A RegExp matching any of the properties as a whole declaration name,
 * so `height` does not match `min-height` or `line-height`.
 */
function property(...names: string[]): RegExp {
  return new RegExp(String.raw`(?<![\w-])(?:${names.join('|')})\s*:`, 'i');
}

/**
 * @param source - A regex fragment for a CSS value (keyword or function).
 * @returns A RegExp matching the value when not preceded by a word character or hyphen.
 */
function value(source: string): RegExp {
  return new RegExp(String.raw`(?<![\w-])(?:${source})`, 'i');
}

