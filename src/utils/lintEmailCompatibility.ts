// Declaration values that reset a property and can't break rendering (e.g. `margin:0`)
const NEUTRAL_VALUE_PATTERN =
  /^(?:0(?:px|em|rem|%)?|none|normal|initial|inherit|unset)(?:\s*!important)?$/i;

// Image formats by caniemail slug (file extensions and data URL subtypes)
const IMAGE_FORMATS: Record<string, string[]> = {
  'image-apng': ['apng'],
  'image-avif': ['avif'],
  'image-bmp': ['bmp'],
  'image-gif': ['gif'],
  'image-heif': ['heif', 'heic'],
  'image-ico': ['ico', 'x-icon', 'vnd.microsoft.icon'],
  'image-jpg': ['jpg', 'jpeg'],
  'image-png': ['png'],
  'image-svg': ['svg', 'svg+xml'],
  'image-tiff': ['tif', 'tiff'],
  'image-webp': ['webp'],
};

/**
 * Derives an HTML selector for a given Caniemail feature slug.
 *
 * @param slug - The Caniemail feature slug.
 * @returns The corresponding HTML selector.
 */
function deriveHtmlSelector(slug: string): string {
  if (Object.hasOwn(HTML_SELECTORS, slug)) return HTML_SELECTORS[slug];
  const name = slug.slice('html-'.length);
  if (name.startsWith('input-'))
    return `input[type="${name.slice('input-'.length)}"]`;
  if (name.startsWith('button-'))
    return `button[type="${name.slice('button-'.length)}"]`;
  if (name.startsWith('aria-')) return `[${name}]`;
  return name;
}

/**
 * Derives a CSS pattern for a given Caniemail feature slug, if applicable.
 *
 * @param slug - The Caniemail feature slug.
 * @returns A RegExp pattern to match the CSS feature or null if not applicable.
 */
function deriveCssPattern(slug: string): RegExp | null {
  if (Object.hasOwn(CSS_PATTERNS, slug)) return CSS_PATTERNS[slug];
  // css-at-{name}
  if (slug.startsWith('css-at-')) {
    const name = slug.slice('css-at-'.length);
    if (name.startsWith('media-')) {
      const feature = name.slice('media-'.length);
      return new RegExp(String.raw`@media[^{]*\b${feature}\b`, 'i');
    }
    return new RegExp(String.raw`@${name}\b`, 'i');
  }
  // css-pseudo-class-{name}
  if (slug.startsWith('css-pseudo-class-'))
    return new RegExp(
      String.raw`(?<!:):${slug.slice('css-pseudo-class-'.length)}\b`,
      'i'
    );
  // css-pseudo-element-{name}
  if (slug.startsWith('css-pseudo-element-'))
    return new RegExp(
      String.raw`::?${slug.slice('css-pseudo-element-'.length)}\b`,
      'i'
    );
  // css-selector-* — too structural for a simple regex, skip
  if (slug.startsWith('css-selector-')) return null;
  // css-display-{value}
  if (slug.startsWith('css-display-')) {
    const displayValue = slug.slice('css-display-'.length);
    return new RegExp(
      String.raw`(?<![\w-])display\s*:[^;]*\b(inline-)?${displayValue}\b`,
      'i'
    );
  }
  // css-unit-{unit}
  if (slug.startsWith('css-unit-')) {
    const unit = slug.slice('css-unit-'.length);
    return new RegExp(String.raw`[\d.]${unit}\b`, 'i');
  }
  // css-function-{fn}
  if (slug.startsWith('css-function-')) {
    return value(String.raw`${slug.slice('css-function-'.length)}\(`);
  }
  // Default css-{property}
  return property(slug.slice('css-'.length));
}

/**
 * @param slug - The Caniemail feature slug.
 * @returns Whether the feature can only appear in a `style` block (selectors, at-rules, nesting).
 */
function isStylesheetOnly(slug: string): boolean {
  return (
    slug.startsWith('css-at-') ||
    slug.startsWith('css-pseudo-') ||
    slug.startsWith('css-selector-') ||
    slug === 'css-nesting'
  );
}

/**
 * @param src - The image source URL.
 * @returns The lowercase image format (extension or data URL subtype), if detectable.
 */
function getImageFormat(src: string): string | undefined {
  const dataFormat = /^data:image\/(?<format>[\w.+-]+)/i.exec(src)?.groups
    ?.format;
  if (dataFormat) return dataFormat.toLowerCase();
  try {
    const { pathname } = new URL(src);
    return /\.(?<ext>[a-z0-9]+)$/i.exec(pathname)?.groups?.ext.toLowerCase();
  } catch {
    return undefined;
  }
}

/**
 * Finds the first occurrence of a Caniemail feature in the email content.
 *
 * @param slug - The Caniemail feature slug.
 * @param context - The parsed email content to search within.
 * @returns The matched source, and the element or pattern used to locate it in the markup.
 */
function findFeature(
  slug: string,
  context: FeatureContext
): FeatureMatch | undefined {
  const findImage = (predicate: (src: string) => boolean) => {
    const image = context.images.find((el) =>
      predicate(String(el.getAttribute('src')))
    );
    return image
      ? { source: String(image.getAttribute('src')), element: image }
      : undefined;
  };
  if (slug === 'image-base64') {
    return findImage((src) => /^data:[^,]*;base64,/i.test(src));
  }
  if (Object.hasOwn(IMAGE_FORMATS, slug)) {
    const formats = IMAGE_FORMATS[slug];
    return findImage((src) => {
      const format = getImageFormat(src);
      return format !== undefined && formats.includes(format);
    });
  }
  if (slug.startsWith('html-')) {
    const el = context.root.querySelector(deriveHtmlSelector(slug));
    if (!el) return undefined;
    return {
      source: el.outerHTML.slice(0, el.outerHTML.indexOf('>') + 1),
      element: el,
    };
  }
  const pattern = deriveCssPattern(slug);
  if (!pattern) return undefined;
  const css = isStylesheetOnly(slug)
    ? context.stylesheetCss
    : `${context.inlineCss}\n${context.stylesheetCss}`;
  const globalPattern = new RegExp(pattern.source, `${pattern.flags}g`);
  for (const match of css.matchAll(globalPattern)) {
    if (!match[0].trimEnd().endsWith(':')) {
      return { source: match[0], pattern };
    }
    const [declarationValue] = css
      .slice(match.index + match[0].length)
      .split(/[;\n]/, 1);
    if (NEUTRAL_VALUE_PATTERN.test(declarationValue.trim())) continue;
    return { source: `${match[0]}${declarationValue}`, pattern };
  }
  return undefined;
}

/**
 * @param client - The caniemail client family key.
 * @param platform - The caniemail platform key.
 * @returns A human-readable client label, e.g. "Gmail Android" or "Outlook.com".
 */
function getClientLabel(client: string, platform: string): string {
  const family = CANIEMAIL_NICENAMES.family[client];
  const platformLabel = CANIEMAIL_NICENAMES.platform[platform];
  return platformLabel.includes(family)
    ? platformLabel
    : `${family} ${platformLabel}`;
}

/**
 * Collects the selected clients that don't support, or only partially
 * support, a feature (based on the latest tested version), plus the
 * caniemail notes explaining the limitations. Unknown support is ignored.
 *
 * @param feature - The Caniemail feature being checked.
 * @param emailClients - The set of client keys to check.
 * @returns The unsupported clients, partially supported clients and notes.
 */
function getClientSupport(
  feature: CaniemailFeature,
  emailClients: Set<string>
) {
  const unsupported = new Set<string>();
  const partial = new Set<string>();
  const notes = new Set<string>();
  for (const [client, platforms] of Object.entries(feature.stats)) {
    if (!emailClients.has(client)) continue;
    for (const [platform, versions] of Object.entries(platforms)) {
      const [status, ...noteRefs] = String(
        Object.values(versions).at(-1)
      ).split(' ');
      if (status !== 'n' && status !== 'a') continue;
      const label = getClientLabel(client, platform);
      (status === 'n' ? unsupported : partial).add(label);
      for (const noteRef of noteRefs) {
        const note = feature.notes_by_num?.[noteRef.slice(1)];
        if (note) notes.add(formatNote(note));
      }
    }
  }
  const sort = (values: Set<string>) =>
    [...values].toSorted((a, b) => a.localeCompare(b));
  return {
    unsupported: sort(unsupported),
    partial: sort(partial),
    notes: [...notes],
  };
}

/**
 * @param note - A caniemail note in markdown.
 * @returns The note as plain text (code spans and link URLs removed).
 */
function formatNote(note: string): string {
  return note
    .replaceAll(/\[(?<text>[^\]]+)\]\([^)]*\)/g, '$<text>')
    .replaceAll('`', '');
}

/**
 * React Email wraps the content in a full-width layout table whose cell holds
 * the `dir`/`lang` attributes and the body styles. That wrapper is generated,
 * so linting starts inside it when present.
 *
 * @param body - The parsed `body` element.
 * @returns The element whose descendants hold the editable content.
 */
function getContentRoot(body: HTMLElement): Element {
  return (
    body.querySelector(
      ':scope > table > tbody > tr > td[lang], :scope > table > tbody > tr > td[dir]'
    ) ?? body
  );
}

/**
 * Finds the offset of an element's opening tag in the raw markup by counting
 * preceding tags with the same name (DOM order matches source order).
 * Comments are masked so tags inside conditional comments are not counted.
 *
 * @param markup - The full HTML markup.
 * @param element - The parsed element to locate.
 * @returns The offset of the element's opening tag, or -1 if not found.
 */
function getElementOffset(markup: string, element: Element): number {
  const tag = element.tagName.toLowerCase();
  const index = [...element.ownerDocument.querySelectorAll(tag)].indexOf(
    element
  );
  const masked = markup.replaceAll(/<!--[\s\S]*?-->/g, (comment) =>
    ' '.repeat(comment.length)
  );
  const pattern = new RegExp(String.raw`<${tag}(?=[\s/>])`, 'gi');
  let count = 0;
  for (const match of masked.matchAll(pattern)) {
    if (count === index) return match.index;
    count += 1;
  }
  return -1;
}

/**
 * @param markup - The full HTML markup.
 * @param root - The content root element.
 * @returns The offset right after the content root's opening tag.
 */
function getContentOffset(markup: string, root: Element): number {
  const rootOffset = getElementOffset(markup, root);
  if (rootOffset === -1) return 0;
  if (root.tagName === 'BODY') return rootOffset;
  return markup.indexOf('>', rootOffset) + 1;
}

/**
 * @param markup - The full HTML markup.
 * @param match - The matched feature.
 * @param fromIndex - The offset to start searching from.
 * @returns The location of the matched feature in the markup.
 */
function getMatchLocation(
  markup: string,
  match: FeatureMatch,
  fromIndex: number
) {
  if (match.element) {
    const offset = getElementOffset(markup, match.element);
    if (offset !== -1) return getCodeLocation(markup, offset);
  }
  const sourceOffset = markup.indexOf(match.source, fromIndex);
  if (sourceOffset !== -1) return getCodeLocation(markup, sourceOffset);
  const patternIndex = match.pattern?.exec(markup.slice(fromIndex))?.index;
  if (patternIndex !== undefined) {
    return getCodeLocation(markup, fromIndex + patternIndex);
  }
  return findCodeLocation(markup, match.source.slice(0, 64), fromIndex);
}

/**
 * Scans the email body for features with limited email-client support and
 * returns a list of compatibility issues. The document shell generated by
 * React Email (doctype, `html`, `head`, `body`, the layout wrapper and
 * theme `style` blocks) is ignored because it can't be changed from the editor.
 *
 * @param markup - The full HTML string of the email to lint.
 * @param emailClients - The set of email client keys to check against.
 * @returns Compatibility issues, unsupported features first, then by title.
 */
export function lintEmailCompatibility(
  markup: string,
  emailClients: Set<string>
): CompatibilityResult[] {
  const { body } = new DOMParser().parseFromString(markup, 'text/html');
  const root = getContentRoot(body);
  const contentOffset = getContentOffset(markup, root);
  const context: FeatureContext = {
    root,
    inlineCss: Array.from(root.querySelectorAll('[style]'), (el) =>
      String(el.getAttribute('style'))
    ).join('\n'),
    stylesheetCss: Array.from(
      root.querySelectorAll('style'),
      (el) => el.textContent
    ).join('\n'),
    images: [...root.querySelectorAll<HTMLImageElement>('img[src]')],
  };
  const results: CompatibilityResult[] = [];
  for (const feature of CANIEMAIL_FEATURES) {
    if (SKIPPED_SLUGS.has(feature.slug)) continue;
    const match = findFeature(feature.slug, context);
    if (!match) continue;
    const support = getClientSupport(feature, emailClients);
    if (support.unsupported.length === 0 && support.partial.length === 0)
      continue;
    results.push({
      title: feature.title,
      category: feature.category,
      severity: support.unsupported.length > 0 ? 'warning' : 'info',
      unsupportedClients: support.unsupported,
      partialClients: support.partial,
      notes: support.notes,
      url: feature.url,
      source: match.source,
      location: getMatchLocation(markup, match, contentOffset),
    });
  }
  return results.toSorted((a, b) => {
    if (a.severity !== b.severity) return a.severity === 'warning' ? -1 : 1;
    return a.title.localeCompare(b.title);
  });
}
